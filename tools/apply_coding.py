"""Deliver the user's CAFD 00000DED coding (coding/*.ncd) to the firmware.

The HMI receives its coding from boot/lib/libnbt_offline_syset.so, which embeds
the coding as a native DSI stream at build time
(work/graphics-port/syset-native/offline-provider/README.md). When the NCD no
longer matches the stream inside the selected IFS, the provider is rebuilt with
the new coding and a separate IFS copy is written to outputs/coding-build/.
The shipped IFS images are never modified. Rebuilt images are cached per NCD.
Usage:
  py -3 tools/apply_coding.py [SOURCE.ifs]   (prints the IFS to boot)
"""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(ROOT / 'work/startup-analysis'))
from inspect_nbt_ifs import find_imagefs
from repack_nbt_ifs import repack
from startup_screen import NCD, read_ncd

PROVIDER = ROOT / 'work/graphics-port/syset-native/offline-provider/offline_syset_provider.c'
ZIG = ROOT / 'work/graphics-port/toolchain/zig-x86_64-windows-0.15.2/zig.exe'
BUILD = ROOT / 'outputs/coding-build'
LIBRARY = 'boot/lib/libnbt_offline_syset.so'
DEFAULT_IFS = ROOT / 'work/bridge-v2/ifs/walthread_keyboard_dma_v2_prio.ifs'
# Native CB slots 0x3000..0x3007 and their sizes in HmiMain3D's metadata.
BLOCK_LENGTHS = [152, 151, 150, 150, 150, 150, 8, 132]
TELEPHONE_KEYS = 5


def coding_stream(ncd=NCD):
    """Native DSI stream of the NCD (format: offline-provider/README.md).
    A CB missing from the NCD (e.g. a removed 0x3007 signature) is sent with
    state 0, so the HMI keeps that node as it is."""
    memory = read_ncd(Path(ncd))
    blocks = []
    for index, length in enumerate(BLOCK_LENGTHS):
        base = 0x300000 + 0x100 * index
        present = [memory.get(base + offset) for offset in range(length)]
        if all(byte is None for byte in present):
            blocks.append(None)
        elif None in present or base + length in memory:
            raise ValueError(f'CB {0x3000 + index:#x} must have exactly {length} bytes')
        else:
            blocks.append(bytes(present))
    if blocks[6] is None:
        raise ValueError('CB 0x3006 (CAF_ID with the coding version) is missing')
    version = tuple(blocks[6][5:8])
    if version[0] != 3:
        raise ValueError(f'Coding major version {version[0]} is not supported (expected 3)')
    children = b''.join(bytes([1, *version]) + struct.pack('<H', len(block)) + block
                        if block is not None else b'\0' for block in blocks) + bytes(TELEPHONE_KEYS)
    # Logged by the provider; same definition as the original build (concatenated CBs).
    source_hash = hashlib.sha256(b''.join(block for block in blocks if block is not None)).hexdigest()
    return struct.pack('<HHH', 1, 1, len(children)) + children, version, source_hash


def _image_file(data, path):
    entry = next((e for e in find_imagefs(data)['entries'] if e['path'] == path), None)
    return entry and data[entry['absolute_offset']:entry['absolute_offset'] + entry['size']]


def build_provider(stream, version, source_hash, directory):
    """Compile the provider with this stream, with the original build flags."""
    header = ['/* Generated by tools/apply_coding.py from the user NCD. */',
              f'#define NBT_CODING_MAJOR {version[0]}', f'#define NBT_CODING_MINOR {version[1]}',
              f'#define NBT_CODING_PATCH {version[2]}', f'#define NBT_CODING_SOURCE_SHA256 "{source_hash}"',
              'static const unsigned char nbt_native_coding_dsi[] = {']
    header += ['    ' + ','.join(f'0x{x:02x}' for x in stream[i:i + 16]) + ',' for i in range(0, len(stream), 16)]
    header.append('};')
    (directory / 'coding_payload.h').write_text('\n'.join(header) + '\n', encoding='ascii')
    library = directory / 'libnbt_offline_syset.so'
    subprocess.run([str(ZIG), 'cc', '-target', 'x86-linux-gnu', '-mcpu=pentium4', '-mstackrealign', '-fPIC',
                    '-ffreestanding', '-fno-builtin', '-fno-stack-protector', '-nostdlib', '-O2', '-shared',
                    '-Wl,--hash-style=sysv', '-Wl,-z,norelro', '-Wl,-soname,libnbt_offline_syset.so',
                    '-I', str(directory), str(PROVIDER), '-o', str(library)],
                   cwd=directory, check=True, capture_output=True)
    if stream not in library.read_bytes():
        raise ValueError('Built provider does not contain the coding stream')
    return library


def coded_ifs(source=DEFAULT_IFS, ncd=NCD, on_rebuild=None):
    """(IFS to boot, status) for the NCD. status: 'unchanged' (the source IFS
    already carries this coding), 'cached', 'rebuilt' or 'unsupported' (the
    image has no coding provider). on_rebuild() is called before a rebuild."""
    source = Path(source)
    data = source.read_bytes()
    provider = _image_file(data, LIBRARY)
    if provider is None:
        return source, 'unsupported'
    stream, version, source_hash = coding_stream(ncd)
    if stream in provider:
        return source, 'unchanged'
    identity = {'stream': hashlib.sha256(stream).hexdigest(), 'source': hashlib.sha256(data).hexdigest(),
                'provider': hashlib.sha256(PROVIDER.read_bytes()).hexdigest(), 'version': 1}
    key = hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:16]
    output = BUILD / f'{source.stem}_coding_{key}.ifs'
    if output.exists():
        return output, 'cached'
    if on_rebuild:
        on_rebuild()
    directory = BUILD / ('build-' + key)
    directory.mkdir(parents=True, exist_ok=True)
    library = build_provider(stream, version, source_hash, directory)
    manifest = repack(source, output, {LIBRARY: library})
    manifest.update(ncd=str(ncd), coding_version='.'.join(map(str, version)), identity=identity)
    output.with_suffix('.manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    return output, 'rebuilt'


if __name__ == '__main__':
    image, status = coded_ifs(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_IFS,
                              on_rebuild=lambda: print('CAFD changed: rebuilding the firmware image...', flush=True))
    print(status, image)
